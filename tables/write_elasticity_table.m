%% write_elasticity_table.m — Combined elasticity table
%
% Panel A (aggregate equation):      demand elasticity  phi_d.
% Panel B (disaggregated equation):  supply elasticity  phi_s, equal weights.
%
% Each panel has three rows: OLS, then the GIV point estimate with two standard
% errors (naive, corrected). The two GIV rows share one point estimate; only
% the SE changes.
%
% Inputs:
%   results_cell  — cell array of structs from make_tables.m (one per commodity)
%   filepath      — full output path for .tex file

function write_elasticity_table(results_cell, filepath)

n = numel(results_cell);

fid = fopen(filepath, 'w');
fprintf(fid, '%% elasticity.tex — OLS and GIV elasticity estimates\n');
fprintf(fid, '%% Generated by tables/make_tables.m on %s\n\n', ...
    datestr(now, 'yyyy-mm-dd'));
fprintf(fid, '\\begin{table}[htbp]\n');
fprintf(fid, '\\centering\n');
fprintf(fid, '\\caption{Price Elasticities of Demand and Supply: OLS and GIV}\n');
fprintf(fid, '\\label{tab:elasticity}\n');

col_spec = ['l', repmat('c', 1, n)];
fprintf(fid, '\\footnotesize\n');
fprintf(fid, '\\setlength{\\tabcolsep}{4pt}\n');   % keeps the table inside \textwidth
fprintf(fid, '\\begin{tabular}{%s}\n', col_spec);
fprintf(fid, '\\toprule\n');

% Header row 1: commodity names
fprintf(fid, 'Estimator');
for k = 1:n
    fprintf(fid, ' & %s', results_cell{k}.commodity);
end
fprintf(fid, ' \\\\\n');

% Header row 2: panel description and N
fprintf(fid, ' ');
for k = 1:n
    fprintf(fid, ' & %s ($N=%d$)', results_cell{k}.panel_desc, results_cell{k}.N);
end
fprintf(fid, ' \\\\\n');
fprintf(fid, '\\midrule\n');

% Panel A — demand
fprintf(fid, '\\multicolumn{%d}{l}{\\textit{Panel A: Demand, aggregate equation ($\\phi_d$)}} \\\\\n', n + 1);
write_panel(fid, results_cell, 'phi_ols_d', 'se_ols_d', 'phi_d', {'se_d_naive', 'se_d_corr'});

fprintf(fid, '\\addlinespace\n');

% Panel B — supply
fprintf(fid, '\\multicolumn{%d}{l}{\\textit{Panel B: Supply, disaggregated equation ($\\phi_s$)}} \\\\\n', n + 1);
write_panel(fid, results_cell, 'phi_ols_s', 'se_ols_s', 'phi_s', {'se_s_naive', 'se_s_corr'});

fprintf(fid, '\\bottomrule\n');
fprintf(fid, '\\end{tabular}\n\n');

% ---- Notes ----
fprintf(fid, '\\vspace{4pt}\n');
fprintf(fid, '\\raggedright\\footnotesize\n');
fprintf(fid, '\\textit{Notes:} Standard errors in parentheses. ');
fprintf(fid, 'Panel A reports the demand elasticity $\\phi_d$ from the aggregate equation; ');
fprintf(fid, 'Panel B the supply elasticity $\\phi_s$ from the disaggregated equation with the ');
fprintf(fid, 'equal-weights aggregator $H = e_N/N$. ');
fprintf(fid, 'OLS is endogenous: common shocks bias it toward zero, and sign reversal is possible. ');
fprintf(fid, 'GIV (Gabaix and Koijen, 2024): idiosyncratic supply shocks to large producers ');
fprintf(fid, 'instrument for price. The two GIV rows share a single point estimate and differ ');
fprintf(fid, 'only in the standard error. The naive SE treats the estimated factor structure, ');
fprintf(fid, 'and hence the instrument, as known. The corrected SE, developed in this paper, ');
fprintf(fid, 'accounts for estimating the factor structure used to construct the instrument. ');
fprintf(fid, 'Factors and the instrument are built from the demeaned panel; the controls $X$ ');
fprintf(fid, 'enter only at the second stage. ');
fprintf(fid, 'All standard errors are HAC (Newey--West, Bartlett kernel, bandwidth ');
fprintf(fid, '$\\lfloor 1.3\\sqrt{T}\\rfloor$). ');
fprintf(fid, 'Control sets differ by commodity. ');
fprintf(fid, 'Year-on-year midpoint growth transformation throughout.\n');
fprintf(fid, '\\end{table}\n');
fclose(fid);

end


function write_panel(fid, results_cell, f_ols, f_se_ols, f_phi, se_fields)
% One panel: an OLS row, then two GIV rows sharing f_phi.

n = numel(results_cell);

% OLS row — its own point estimate
fprintf(fid, '\\quad OLS');
for k = 1:n
    res = results_cell{k};
    fprintf(fid, ' & %.4f (%.4f)', res.(f_ols), res.(f_se_ols));
end
fprintf(fid, ' \\\\\n');

% GIV rows — one point estimate, two SEs
labels = {'GIV --- naive SE', 'GIV --- corrected SE'};
for j = 1:numel(labels)
    fprintf(fid, '\\quad %s', labels{j});
    for k = 1:n
        res = results_cell{k};
        fprintf(fid, ' & %.4f (%.4f)', res.(f_phi), res.(se_fields{j}));
    end
    fprintf(fid, ' \\\\\n');
end

end
